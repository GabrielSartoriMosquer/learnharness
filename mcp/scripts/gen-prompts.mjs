// Generates src/generated/prompts.ts from the app's prompt sources at build
// time, so the Worker composes the same doctrine the desktop does and
// inherits upstream doctrine changes on every deploy. Composition rules live
// in src/doctrine.ts; this only snapshots the files.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mcpRoot = path.resolve(here, "..");
const appPrompts = path.resolve(mcpRoot, "../src/agent/prompts");
const systemPrompt = path.resolve(mcpRoot, "../src/agent/system-prompt.md");
const FRAGMENT_RE = /^\d+-[\w.-]+\.md$/;

const read = (file) => fs.readFileSync(file, "utf-8");
const fragments = (dir) =>
	fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => FRAGMENT_RE.test(f)).sort() : [];

const app = { "system-prompt.md": read(systemPrompt) };
for (const agent of ["prober", "teacher", "practice", "shared"]) {
	for (const f of fragments(path.join(appPrompts, agent))) app[`${agent}/${f}`] = read(path.join(appPrompts, agent, f));
}
const mcp = {};
for (const f of fragments(path.join(mcpRoot, "prompts"))) mcp[`mcp/${f}`] = read(path.join(mcpRoot, "prompts", f));

const out = path.join(mcpRoot, "src/generated/prompts.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
	out,
	"// GENERATED by scripts/gen-prompts.mjs — do not edit.\n" +
		`export const APP_SEGMENTS: Record<string, string> = ${JSON.stringify(app, null, "\t")};\n` +
		`export const MCP_SEGMENTS: Record<string, string> = ${JSON.stringify(mcp, null, "\t")};\n`,
);
console.log(`prompts: ${Object.keys(app).length} app segments, ${Object.keys(mcp).length} MCP segments`);
